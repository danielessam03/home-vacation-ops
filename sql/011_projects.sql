-- HV OPS — 011_projects.sql   (Daniel, 2026-09-19)
-- Projects (developer compounds / resorts) go through the same two-stage pipeline as units:
--   ENTRY (data + photos)  ->  ready  ->  UPLOAD to the website  ->  verified live by the verifier.
-- What the website shows (checked on all 54 live projects): a "Project ID" in the Technical Specifications block.
--   Company convention:  P-LOC-SERIAL-S      e.g. P-MG-929-S, P-VR-925-S, P-G-918-S
--     P = project, LOC = same location letters as units, SERIAL = the projects' OWN running number (separate from units;
--     highest on the site is 929, so the next is 930), S = sale.
--   IDs like PRJ-013330 are NOT company codes: the website fills in the WordPress post number when nobody typed a Project ID.
-- Column names deliberately match ops_listings so the same guard / stamps / audit trigger functions are reused.
-- Additive, safe to re-run.

create table if not exists ops_projects (
  id uuid primary key default gen_random_uuid(),
  reference_code text unique not null,               -- P-MG-930-S, generated by trigger; pasted into WordPress "Project ID"
  name text not null,
  developer text,
  location text not null,
  project_types text[] default '{}',                 -- Apartment / Villa / Resort / Compound ... (website "project_type")
  unit_sizes text,                                   -- "57 – 180 m² (Studios, 1BR, 2BR)"
  bedrooms text,                                     -- "Studio, 1–3 BR"
  starting_price numeric,
  currency text,                                     -- never converted
  down_payment text,                                 -- "10%"
  installments text,                                 -- "7 years, quarterly"
  delivery_date text,                                -- "December 2027" / "3 years from contract" / "Available"
  finishing text,
  facilities text[] default '{}',
  selling_points text,
  is_exclusive boolean,
  media_uploaded boolean,                            -- photos/brochure ready = approved by the manager (files stay on the intranet)
  media_has_logo boolean,
  media_edited boolean,
  media_approved_by uuid references public.app_users(id),
  media_approved_at timestamptz,
  source_name text,                                  -- developer's contact person
  source_contact text,
  date_received timestamptz not null default now(),  -- SLA clock start
  date_ready timestamptz,
  date_published_claimed timestamptz,
  published_claimed_by uuid references public.app_users(id),
  date_published_verified timestamptz,               -- verifier only
  entered_by uuid not null references public.app_users(id),
  assigned_to uuid references public.app_users(id),
  status ops_listing_status not null default 'draft',
  status_before_hold ops_listing_status,
  hold_reason text,
  hold_started_at timestamptz,
  paused_seconds bigint not null default 0,
  rejection_reason text,
  completeness_pct int not null default 0,
  missing_fields text[] default '{}',
  website_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists ops_idx_projects_status on ops_projects(status);
create index if not exists ops_idx_projects_entered_by on ops_projects(entered_by);
create index if not exists ops_idx_projects_assigned_to on ops_projects(assigned_to);

create table if not exists ops_wp_project_index (
  id uuid primary key default gen_random_uuid(),
  reference_code text not null unique,
  url text,
  wp_published_at timestamptz,
  first_seen_at timestamptz not null default now(),
  method text,
  raw jsonb
);

