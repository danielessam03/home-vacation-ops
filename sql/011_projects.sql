-- ---------------------------------------------------------------- completeness: the required-field list is chosen per table
-- trigger argument = the ops_settings key to read (default: required_fields, i.e. units)
create or replace function ops_fn_calc_completeness() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  req jsonb; row_j jsonb := to_jsonb(new); f text; v jsonb;
  total int := 0; filled int := 0; missing text[] := '{}';
  list_key text := coalesce(tg_argv[0], 'required_fields');
begin
  select value into req from ops_settings where key = list_key;
  if req is null or jsonb_typeof(req) <> 'array' then return new; end if;

  for f in select jsonb_array_elements_text(req) loop
    if not (row_j ? f) then continue; end if;
    total := total + 1;
    v := row_j -> f;
    if v is null or jsonb_typeof(v) = 'null'
       or (jsonb_typeof(v) = 'string' and btrim(v #>> '{}') = '')
       or (jsonb_typeof(v) = 'array'  and jsonb_array_length(v) = 0)
       or (f in ('media_images_count','media_videos_count','area_sqm','price','starting_price') and jsonb_typeof(v) = 'number' and (v #>> '{}')::numeric <= 0)
       or (f = 'media_uploaded' and v = 'false'::jsonb)
    then missing := array_append(missing, f);
    else filled := filled + 1;
    end if;
  end loop;

  new.completeness_pct := case when total = 0 then 100 else floor(100.0 * filled / total)::int end;
  new.missing_fields := missing;
  return new;
end $$;

-- ---------------------------------------------------------------- project code  P-LOC-SERIAL-S , serial = last project serial + 1
create or replace function ops_fn_generate_project_code() returns trigger
language plpgsql security definer set search_path = public as $$
declare loc_code text; n bigint; candidate text;
begin
  if new.reference_code is not null and btrim(new.reference_code) <> '' then
    new.reference_code := upper(regexp_replace(new.reference_code, '\s', '', 'g'));   -- importing an existing project keeps the site's ID
    return new;
  end if;
  select value ->> new.location into loc_code from ops_settings where key = 'location_codes';
  if loc_code is null then raise exception 'No location code for "%". Add it in Settings > Location codes.', new.location; end if;

  perform pg_advisory_xact_lock(hashtext('ops_project_serial'));
  -- only real company codes count (P-…-###-S); website auto-IDs such as PRJ-013330 are ignored
  select coalesce(max((regexp_match(upper(reference_code), '-(\d{1,6})-S$'))[1]::bigint), 0) + 1 into n
  from (select reference_code from ops_wp_project_index union all select reference_code from ops_projects) r
  where upper(reference_code) ~ '^P-.*-\d{1,6}-S$';

  loop
    candidate := 'P-' || upper(loc_code) || '-' || n || '-S';
    exit when not exists (select 1 from ops_projects where reference_code = candidate)
          and not exists (select 1 from ops_wp_project_index where upper(reference_code) = candidate);
    n := n + 1;
  end loop;
  new.reference_code := candidate;
  return new;
end $$;

